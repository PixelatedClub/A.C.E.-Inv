def _item_without_category_prefix(value: str) -> str:
    for prefix in ("AFROTC PT ", "OCP ", "PTG ", "Blues ", "Blue "):
        if value.startswith(prefix):
            return value[len(prefix):]
    return value


ITEM_NAME_ALIASES = {
    value: _item_without_category_prefix(value)
    for value in DEFAULT_ITEM_NAMES
    if _item_without_category_prefix(value) != value
}
DEFAULT_ITEM_NAMES = list(dict.fromkeys(_item_without_category_prefix(value) for value in DEFAULT_ITEM_NAMES))


